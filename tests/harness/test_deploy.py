"""Deploy: the RELATED_IMAGE_* mapping and the image record it keeps in step."""

from __future__ import annotations

import pytest

from harness import deploy
from harness.config import IMAGES_ENV_DEPLOYED_MARKER, Settings, is_deployed_record
from harness.shell import HarnessError


def test_the_workload_image_is_always_handed_over():
    variables = dict(deploy.related_image_env(Settings()))
    assert variables["RELATED_IMAGE_ODH_TRUSTYAI_SERVICE_OPERATOR_IMAGE"] == Settings().workload_img
    assert "RELATED_IMAGE_ODH_EVAL_HUB_IMAGE" not in variables


def test_each_operand_image_named_becomes_its_related_image():
    settings = Settings(
        evalhub_img="quay.io/me/evalhub:mine",
        lmes_img="quay.io/me/lmes:mine",
        inspect_img="quay.io/me/inspect:mine",
        lighteval_img="quay.io/me/lighteval:mine",
        kube_rbac_proxy_img="quay.io/me/proxy:mine",
    )
    variables = dict(deploy.related_image_env(settings))
    assert variables["RELATED_IMAGE_ODH_EVAL_HUB_IMAGE"] == "quay.io/me/evalhub:mine"
    assert variables["RELATED_IMAGE_ODH_TA_LMES_JOB_IMAGE"] == "quay.io/me/lmes:mine"
    assert variables["RELATED_IMAGE_ODH_EVAL_HUB_INSPECTAI_IMAGE"] == "quay.io/me/inspect:mine"
    assert variables["RELATED_IMAGE_ODH_EVAL_HUB_LIGHTEVAL_IMAGE"] == "quay.io/me/lighteval:mine"
    assert variables["RELATED_IMAGE_ODH_KUBE_RBAC_PROXY_IMAGE"] == "quay.io/me/proxy:mine"
    assert variables["RELATED_IMAGE_ODH_TRUSTYAI_SERVICE_PY_IMAGE"] == Settings().trustyai_service_img


def test_an_image_the_deploy_does_not_use_is_dropped_from_the_record(tmp_path):
    path = tmp_path / "images.env"
    path.write_text(
        "\n".join(
            [
                "# Generated by k8s-tests images-all",
                "WORKLOAD_IMG=localhost:5005/trustyai-service-operator:dev",
                "LMES_IMG=localhost:5005/evalhub/community-lmes:dev",
            ]
        )
    )
    settings = Settings(images_env_file=str(path), workload_img="localhost:5005/trustyai-service-operator:dev")
    kept = deploy.keep_used_images(settings)
    assert kept == ["WORKLOAD_IMG=localhost:5005/trustyai-service-operator:dev"]


def test_a_record_with_nothing_left_is_removed(tmp_path):
    path = tmp_path / "images.env"
    path.write_text("LMES_IMG=localhost:5005/evalhub/community-lmes:dev\n")
    settings = Settings(images_env_file=str(path))
    assert deploy.keep_used_images(settings) is None
    assert not path.exists()


def test_stamping_marks_the_record_as_deployed(tmp_path):
    path = tmp_path / "images.env"
    path.write_text("WORKLOAD_IMG=localhost:5005/trustyai-service-operator:dev\n")
    settings = Settings(images_env_file=str(path), workload_img="localhost:5005/trustyai-service-operator:dev")
    kept = deploy.keep_used_images(settings)
    assert not is_deployed_record(path)
    deploy.stamp_record(settings, kept)
    assert is_deployed_record(path)
    assert IMAGES_ENV_DEPLOYED_MARKER in path.read_text()


def test_deploying_the_registry_record_requires_one(tmp_path):
    settings = Settings(images_env_file=str(tmp_path / "absent.env"))
    with pytest.raises(HarnessError, match="images-all"):
        deploy.registry_deploy(settings)


def test_deploying_the_registry_record_applies_it(tmp_path, monkeypatch):
    path = tmp_path / "images.env"
    path.write_text(
        "\n".join(
            [
                "# Generated by k8s-tests images-all",
                "WORKLOAD_IMG=localhost:5005/trustyai-service-operator:dev",
                "MODULE_IMG=localhost:5005/trustyai-operator-module:dev",
                "EVALHUB_IMG=localhost:5005/evalhub/evalhub:dev",
            ]
        )
    )
    deployed: list[Settings] = []
    monkeypatch.setattr(deploy, "deploy", deployed.append)
    deploy.registry_deploy(Settings(images_env_file=str(path)))
    assert deployed[0].workload_img == "localhost:5005/trustyai-service-operator:dev"
    assert deployed[0].evalhub_img == "localhost:5005/evalhub/evalhub:dev"
